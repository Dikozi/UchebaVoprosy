def check_limits():
    """Проверка лимитов текстов — ворота линтера."""
    bad = []
    for key, t in DAYLINE.items():
        sample = (t.replace("{habit}", "Медитация").replace("{why}", " — спокойствие")
                   .replace("{rec}", "17").replace("{n}", "5").replace("{rank}", "Разгон"))
        if len(sample) > LIMIT_DAYLINE:
            bad.append(f"строка дня «{key}»: {len(sample)} > {LIMIT_DAYLINE}")
    for icon, name, short, freq, why in EXAMPLES:
        if len(name) > LIMIT_NAME:
            bad.append(f"название «{name}»: {len(name)} > {LIMIT_NAME}")
        if len(short) > LIMIT_SHORT:
            bad.append(f"имя «{short}»: {len(short)} > {LIMIT_SHORT}")
        if len(why) > LIMIT_WHY:
            bad.append(f"«Чтобы…» «{why}»: {len(why)} > {LIMIT_WHY}")
    for s in STEPS:
        if len(s.split()) > 12:
            bad.append(f"шаг «{s}»: больше 12 слов")
    return bad
